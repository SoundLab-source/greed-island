export const GLYPH_WIDTH = 5;

/** Whether the font can draw this character (upper or lower case). */
export function hasGlyph(ch: string): boolean {
  return GLYPHS[ch.toUpperCase()] !== undefined;
}

export const GLYPH_HEIGHT = 7;

/** How wide `text` is at `scale` (a pixel of space between letters). */
export function textWidth(text: string, scale = 1): number {
  return text.length ? (text.length * (GLYPH_WIDTH + 1) - 1) * scale : 0;
}

/** Draw `text` (upper-cased) into `img` with its top-left corner at x, y, in palette index `color`. */
export function drawText(img: IndexedImage, text: string, x: number, y: number, color: number, scale = 1): void {
  let cx = x;
  for (const ch of text.toUpperCase()) {
    const glyph = GLYPHS[ch];
    if (!glyph) throw new Error(`no glyph for "${ch}"`);
    for (let gy = 0; gy < GLYPH_HEIGHT; gy++) {
      for (let gx = 0; gx < GLYPH_WIDTH; gx++) {
        if (glyph[gy]![gx] !== "#") continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) {
            const px = cx + gx * scale + sx, py = y + gy * scale + sy;
            if (px >= 0 && py >= 0 && px < img.width && py < img.height) img.pixels[py * img.width + px] = color;
          }
        }
      }
    }
    cx += (GLYPH_WIDTH + 1) * scale;
  }
}
