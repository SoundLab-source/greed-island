/**
 * A template's character code, generated from its spec: the constants file
 * (patched per fight for upgrades, like any character's), the states (intro,
 * win poses, taunt and every attack) and the commands, with the fighter's AI
 * in [Statedef -1].
 *
 * The AI takes full control of the fighter: AssertSpecial NoAIButtonJam and
 * NoAICheat switch off the engine's random button presses, and AssertInput
 * holds directions for walking, crouching and blocking
 * (vendor/Ikemen-GO src/input.go:2673, src/char.go:5360, src/bytecode.go:11941).
 * Shared states (walking, jumping, guarding, getting hit) come from the
 * engine's common1.cns.
 */
import type { AttackSpec, Command, HitSpec, TemplateSpec, ThrowSpec } from "./spec.ts";

/** Round for a .cns file. */
function n(x: number): string {
  const r = Math.round(x * 100) / 100;
  return Object.is(r, -0) ? "0" : String(r);
}

function section(title: string, values: Record<string, string | number>): string {
  return [`[${title}]`, ...Object.entries(values).map(([k, v]) => `${k} = ${typeof v === "number" ? n(v) : v}`)].join("\n");
}

/** How much bigger the character's own units are than 320-wide units. */
export function unitScale(spec: TemplateSpec): number {
  return spec.art.localcoord / 320;
}

