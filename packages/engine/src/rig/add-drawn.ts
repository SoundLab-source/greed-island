/** Adding a drawn fighter (templates/drawn.ts): its PNG into art/parts/, and entries in drawn-fighters.json and roster.json. */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";

interface Roster {
  fighters: { id: string; displayName: string }[];
  characters: { key: string; fighter: string; name: string; palette: number }[];
}

export function drawnId(name: string): string {
  const slug = name.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");
  if (!slug) throw new Error(`"${name}" needs some letters or digits`);
  return `gi-${slug}`;
}

/** Returns the new fighter's id. Refuses a name already used by a fighter or character. */
export async function addDrawnFighter(repoRoot: string, o: { name: string; artist: string; bytes: Uint8Array; sha256: string }): Promise<string> {
  const id = drawnId(o.name);
  const rosterFile = path.join(repoRoot, "packages", "engine", "roster.json");
  const listFile = path.join(repoRoot, "packages", "engine", "drawn-fighters.json");
  const roster = JSON.parse(await readFile(rosterFile, "utf8")) as Roster;
  const list = JSON.parse(await readFile(listFile, "utf8")) as { fighters: { id: string }[] };
  const key = `house-${id.slice(3)}`;
  if (roster.fighters.some((f) => f.id === id || f.displayName === o.name) || roster.characters.some((c) => c.key === key || c.name === o.name) || list.fighters.some((f) => f.id === id)) {
    throw new Error(`there is already a fighter called ${o.name} (${id})`);
  }
  const file = `art/parts/${id.slice(3)}.png`;
  await mkdir(path.join(repoRoot, "art", "parts"), { recursive: true });
  await writeFile(path.join(repoRoot, file), o.bytes);
  list.fighters.push({ id, name: o.name, file, sha256: o.sha256, artist: o.artist } as { id: string });
  await writeFile(listFile, JSON.stringify(list, null, 2) + "\n");
  roster.fighters.push({
    id,
    displayName: o.name,
    archetype: "ALL_ROUNDER",
    rarity: "COMMON",
    def: `chars/${id}/${id}.def`,
    license: `House fighter drawn by ${o.artist} on the Greed Island parts guide (${file}); posed and animated by the rig (packages/engine/src/rig) on the Brawler's moves. Character code generated by Greed Island (pnpm templates:build).`,
    enabled: true,
    commercialUse: true,
  } as Roster["fighters"][number]);
  roster.characters.push({ key, fighter: id, name: o.name, palette: 1 });
  await writeFile(rosterFile, JSON.stringify(roster, null, 2) + "\n");
  return id;
}
